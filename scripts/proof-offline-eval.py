"""Offline, LLM-free evaluation of the proof controller on frozen LoCoMo memories.

It reuses a frozen memory (graph + BGE-M3 vectors + OpenIE facts) produced by
`python -m wrag.controlled` and measures retrieval only: R@5 and AR@5 against
the annotated evidence, and how many contexts change. No answer is generated,
so no F1 is claimed. Two uses:

  calibrate   grid over the score weights (time, importance) for the default
              plan and for plans with a period; the defaults of
              scoring.WeightLevels come from this.
  replay      run a controller with plans replayed from a previous run's
              compiled queries (diagnosticos.planos_compilados), so the proof,
              the context policy and the verification policy can be compared
              with the selective controller on the same facts and plans.

    python scripts/proof-offline-eval.py calibrate \\
        --memories runs/locomo-controlled-01/controlled --locomo data/locomo10.json
    python scripts/proof-offline-eval.py replay --controller proof --verify oracle \\
        --memories runs/locomo-controlled-01/controlled --locomo data/locomo10.json \\
        --plans "runs/locomo-all-b-noverify-simple/conversations/*/benchmark/*/locomo/witnessrag.jsonl"

`--verify oracle` accepts a proof only when a fact comes from an annotated
evidence passage (an upper bound for the verifier); `all` accepts every usable
proof (a lower bound); `none` disables the verification step. Embeddings run on
CPU with BAAI/bge-m3 by default (the model of the frozen vectors).

Pickles are private checkpoints generated by this repository; never load a
memory file from an untrusted source.
"""
