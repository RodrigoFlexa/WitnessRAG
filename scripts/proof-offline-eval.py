from wrag import config as C  # noqa: E402
from wrag.data import Corpus, Question  # noqa: E402
from wrag.embed import get_embedder  # noqa: E402
from wrag.llm.base import LLM, LLMResult  # noqa: E402
from wrag.llm.stub import StubLLM, payload_of  # noqa: E402
from wrag.methods.base import IndexContext  # noqa: E402
from wrag.methods.dense import HybridRetriever  # noqa: E402

CATEGORIES = {1: "multi-hop", 2: "temporal", 3: "open-domain", 4: "single-hop"}
WINDOW = re.compile(
    r"\b(in|during|on|around|of|before|after)\s+((?:early |mid |late |the (?:first|last) week of )?"
    r"(?:(?:\d{1,2} )?(?:January|February|March|April|May|June|July|August|September|October|"
    r"November|December)(?:,? \d{4})?|\d{4}))\b")


def memories(folder: Path, locomo: Path):
    samples = {s["sample_id"]: s for s in json.loads(locomo.read_text(encoding="utf-8"))}
    for path in sorted(folder.glob("*/memory.pkl")):
        kg, extraction = pickle.loads(path.read_bytes())
        sample = re.search(r"LoCoMo (\S+) ", kg.corpus.passages[0].title).group(1)
        yield sample, kg, extraction, samples[sample]


def questions(sample: dict, corpus: Corpus) -> list[Question]:
    where = {}
    for passage in corpus.passages:
        for dia in re.findall(r"^\[(D\d+:\d+)\]", passage.text, re.M):
            where[dia] = passage.pid
    out = []
    for index, qa in enumerate(sample["qa"]):
        if qa["category"] not in CATEGORIES:
            continue
        gold = []
        for ref in qa.get("evidence", []):
            for dia in re.split(r"[;,\s]+", ref.strip()):
                if dia in where and where[dia] not in gold:
                    gold.append(where[dia])
        out.append(Question(qid=f"locomo:{sample['sample_id']}:qa{index}",
                            question=qa["question"], answers=[str(qa.get("answer"))],
                            gold_pids=gold, dataset="locomo",
                            qtype=CATEGORIES[qa["category"]]))
    return out


def context(kg, extraction, embedder, llm=None) -> IndexContext:
    run = C.RunConfig(dataset="locomo")
    w = run.witness
    w.hybrid_fallback = w.binding_aware_grounding = w.answer_set = True
    w.vocabulary_aware_compile = w.gap_context_rescue = True
    corpus = Corpus(name="locomo", passages=kg.corpus.passages, questions=[])
    kg.corpus = corpus
    return IndexContext(corpus=corpus, llm=llm or StubLLM(), embedder=embedder, run=run,
                        extraction=extraction, kg=kg)


def recall(order, gold):
    top = set(order[:5])
    return sum(g in top for g in gold) / len(gold), float(set(gold) <= top)


def summarize(rows):
    out = {}
    for category in ("single-hop", "multi-hop", "temporal", "open-domain"):
        subset = [r for r in rows if r["cat"] == category]
        if not subset:
            continue
        n = len(subset)
        out[category] = {
            "n": n, "r5": 100 * sum(r["r5"] for r in subset) / n,
            "ar5": 100 * sum(r["ar5"] for r in subset) / n,
            "base_r5": 100 * sum(r["base_r5"] for r in subset) / n,
            "base_ar5": 100 * sum(r["base_ar5"] for r in subset) / n,
            "changed": 100 * sum(r["changed"] for r in subset) / n,
            "wins": sum(r["gain"] > 0 for r in subset),
            "losses": sum(r["gain"] < 0 for r in subset)}
    return out


def calibrate(args) -> dict:
    from wrag.witness.dated_memory import DatedMemory
    from wrag.witness.scoring import MemoryScorer, Weights, resolve_period
    embedder = get_embedder("st")
    cases = []
    for sample, kg, extraction, raw in memories(args.memories, args.locomo):
        ctx = context(kg, extraction, embedder)
        hybrid = HybridRetriever(ctx)
        hybrid.index()
        dated = DatedMemory(ctx.corpus, kg.facts)
        scorer = MemoryScorer(dated)
        pids = [p.pid for p in ctx.corpus.passages]
        for q in questions(raw, ctx.corpus):
            if not q.gold_pids:
                continue
            pool, fused = hybrid.search(q.question, 20)
            cases.append((q, pool, dict(zip(pool, fused)), scorer, dated, pids))
        print(sample, len(cases), flush=True)

    def run(select):
        rows = []
        for q, pool, fused, scorer, dated, pids in cases:
            choice = select(q, dated)
            order = pool if choice is None else scorer.rank(fused, pool, pids, *choice)
            r5, ar5 = recall(order, q.gold_pids)
            b5, bar5 = recall(pool, q.gold_pids)
            rows.append({"cat": q.qtype, "r5": r5, "ar5": ar5, "base_r5": b5, "base_ar5": bar5,
                         "changed": set(order[:5]) != set(pool[:5]),
                         "gain": r5 - b5})
        return summarize(rows)

    def window(q, dated):
        match = WINDOW.search(q.question)
        if not match:
            return None
        text = match.group(2)
        if not re.search(r"\d{4}", text) and dated.last:
            text += f" {dated.last.year}"
        period, _ = resolve_period("window", text, dated)
        return period if period.kind == "window" else None

    report = {"baseline": run(lambda q, d: None), "default_now": {}, "window": {}}
    for wt in (0.0, 0.05, 0.1, 0.2):
        for wi in (0.0, 0.05, 0.1, 0.2):
            if wt == wi == 0:
                continue
            weights = Weights(1 - wt - wi, wi, wt)
            report["default_now"][f"t={wt},i={wi}"] = run(
                lambda q, d, w=weights: (w, resolve_period("now", "", d)[0]))
    for wt in (0.1, 0.2, 0.3, 0.5):
        weights = Weights(1 - wt, 0.0, wt)
        report["window"][f"t={wt}"] = run(
            lambda q, d, w=weights: (w, window(q, d)) if window(q, d) else None)
    return report


class ReplayLLM(LLM):
    """Returns recorded compiled queries as plans; periods from the question text."""

    name = "replay"

    def __init__(self, compiles: dict[str, dict]) -> None:
        super().__init__()
        self.compiles = compiles

    def _complete(self, messages, params, stage="misc"):
        payload = payload_of(messages)
        question = payload.strip().splitlines()[-1].strip()
        recorded = self.compiles.get(question)
        if stage == "witness.compile":
            text = json.dumps(recorded or {"answer_var": "x", "atoms": []})
        elif stage in {"witness.plan", "witness.replan_v3"}:
            if not recorded:
                text = json.dumps({"answer_var": "x", "atoms": []})
            else:
                match = WINDOW.search(question)
                first = re.search(r"\bfirst\b", question, re.I)
                text = json.dumps({
                    "answer_var": recorded["answer_var"], "atoms": recorded["atoms"],
                    "aggregation": recorded["aggregation"],
                    "expected_type": recorded.get("expected_type", "other"),
                    "period": ({"reference": "window", "text": match.group(2)} if match else
                               {"reference": "start", "text": ""} if first else
                               {"reference": "now", "text": ""}),
                    "time_weight": "strong" if (match or first) else "normal",
                    "importance_weight": "normal",
                    "fallback": recorded.get("fallback", question)})
        else:
            text = json.dumps({"answer": ""})
        return LLMResult(text=text, prompt_tokens=1, completion_tokens=1, finish_reason="stop")


def replay(args) -> dict:
    import wrag.methods.witnessrag as W
    from wrag.witness.confirm import Verdict

    compiles: dict[str, dict] = {}
    for path in glob.glob(args.plans):
        for line in Path(path).read_text(encoding="utf-8").splitlines():
            row = json.loads(line)
            plans = (row.get("diagnosticos") or {}).get("planos_compilados") or []
            if plans:
                compiles[row["pergunta"].strip()] = plans[0]["consulta"]
    gold_of: dict[str, set[str]] = {}

    def verify(llm, question, plan_text, candidates, dataset="", method=""):
        if args.verify == "all":
            return Verdict(called=True, supported=list(range(len(candidates))), valid=True)
        gold = gold_of[question.qid]
        supported = [i for i, c in enumerate(candidates)
                     if any(f.get("pid") in gold for f in c["facts"])]
        return Verdict(called=True, supported=supported, valid=True,
                       rejected={i: "not_supported" for i in range(len(candidates))
                                 if i not in supported})

    original = W.WitnessRAGRetriever._verification_candidates

    def candidates_with_pids(self, outcome):
        out = original(self, outcome)
        for (_position, witness), candidate in zip(outcome["selecionadas"], out):
            for index, fact in zip(witness.facts, candidate["facts"]):
                fact["pid"] = self.memory.facts[index].pid
        return out

    W.WitnessRAGRetriever._verification_candidates = candidates_with_pids
    W.confirm = verify
    embedder = get_embedder("st")
    rows, routes = [], Counter()
    for sample, kg, extraction, raw in memories(args.memories, args.locomo):
        ctx = context(kg, extraction, embedder, ReplayLLM(compiles))
        w = ctx.run.witness
        if args.controller == "proof":
            w.proof_controller = True
            w.proof_verify = args.verify != "none"
            w.proof_partial_evidence = args.partial_evidence
            w.proof_cycles = args.cycles
        else:
            w.selective_witness = True
        retriever = W.WitnessRAGRetriever(ctx)
        retriever.index()
        for q in questions(raw, ctx.corpus):
            if q.question.strip() not in compiles or not q.gold_pids:
                continue
            gold_of[q.qid] = set(q.gold_pids)
            pool, _ = retriever._dense.search(q.question, w.candidate_pool_k)
            result = retriever.retrieve(q, 5)
            r5, ar5 = recall(result.pids, q.gold_pids)
            b5, bar5 = recall(pool, q.gold_pids)
            rows.append({"cat": q.qtype, "r5": r5, "ar5": ar5, "base_r5": b5,
                         "base_ar5": bar5, "changed": set(result.pids) != set(pool[:5]),
                         "gain": r5 - b5})
            routes[f"{q.qtype}|{result.diagnostics.get('rota')}"] += 1
        print(sample, len(rows), flush=True)
    return {"summary": summarize(rows), "routes": dict(sorted(routes.items()))}


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("command", choices=["calibrate", "replay"])
    p.add_argument("--memories", type=Path, required=True)
    p.add_argument("--locomo", type=Path, required=True)
    p.add_argument("--plans", default="")
    p.add_argument("--controller", choices=["proof", "selective"], default="proof")
    p.add_argument("--verify", choices=["all", "oracle", "none"], default="oracle")
    p.add_argument("--partial-evidence", action="store_true",
                   help="ablation: agreement probes / gap rescue for connected plans")
    p.add_argument("--cycles", type=int, default=1)
    p.add_argument("--output", type=Path)
    args = p.parse_args(argv)
    if args.command == "replay" and not args.plans:
        p.error("replay needs --plans")
    report = calibrate(args) if args.command == "calibrate" else replay(args)
    text = json.dumps(report, indent=2, ensure_ascii=False)
    if args.output:
        args.output.write_text(text + "\n", encoding="utf-8")
    print(text)
    return report


if __name__ == "__main__":
    main()
